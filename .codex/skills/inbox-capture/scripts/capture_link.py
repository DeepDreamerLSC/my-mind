def walk_values(obj: Any, key: str) -> list[Any]:
    found: list[Any] = []
    if isinstance(obj, dict):
        for current_key, value in obj.items():
            if current_key == key:
                found.append(value)
            found.extend(walk_values(value, key))
    elif isinstance(obj, list):
        for item in obj:
            found.extend(walk_values(item, key))
    return found


